import { isBelowVersion } from '@/features/update/version';

describe('버전 비교(결정 027)', () => {
  it.each([
    // [내 버전, 최소 버전, 낮은가]
    ['1.0.0', '1.0.1', true],
    ['1.0.0', '1.1.0', true],
    ['1.0.0', '2.0.0', true],
    ['1.9.9', '1.10.0', true],
    ['1.10.0', '1.9.9', false],
    ['1.2.0', '1.2.0', false],
    ['1.2.1', '1.2.0', false],
    ['2.0.0', '1.99.99', false],
    // 없는 마디는 0 이다
    ['1.2', '1.2.0', false],
    ['1.2.0', '1.2', false],
    ['1', '1.0.1', true],
    ['1.2', '1.2.1', true],
    ['2', '1.9', false],
    ['01.02.0', '1.2.0', false],
  ])('내 버전 %s, 최소 %s → 낮은가 %s', (mine, min, expected) => {
    expect(isBelowVersion(mine, min)).toBe(expected);
  });

  it.each([
    ['1.0.0', null],
    ['1.0.0', ''],
    ['1.0.0', 'latest'],
    ['1.0.0', '2.0.0-beta'],
    ['1.0.0', 'v2.0.0'],
    ['1.0.0', '2..0'],
    ['1.0.0', '2.0.0.1'],
    ['1.0.0', ' 2.0.0'],
    ['1.0.0', '-2.0'],
    ['1.0.0-rc1', '2.0.0'],
    ['', '2.0.0'],
    ['1.0.0.0', '2.0.0'],
    [undefined, '2.0.0'],
    [null, '2.0.0'],
    [100, '2.0.0'],
  ])('읽을 수 없는 값(내 버전 %p, 최소 %p)이면 낮다고 하지 않는다', (mine, min) => {
    expect(isBelowVersion(mine, min)).toBe(false);
  });
});
